
package eva2_22_incrementos_netbeans;


public class EVA2_22_INCREMENTOS_Netbeans {

    
    public static void main(String[] args) {
        
        int i = 1;
        
        //ACUMULADOR:
        //YO QUIERO QUE LA i SE INCREMENTA EN 1
        
        System.out.println("i = " + i);
        i = i + 1; //ACUMULADOR
        System.out.println("i = " + i);
        
        System.out.println("i = " + i);
        i++; //INCREMENTA EN 1 EL VALOR DE LA VARIABLE
        System.out.println("i = " + i);
        
        System.out.println("i = " + i);
        i+=2; //DECREMENTA EN 1 EL VALOR DE LA VARIABLE EN DOS
        System.out.println("i = " + i);
        
        System.out.println("i = " + i);
        i--; //DECREMENTA EN 1 EL VALOR DE LA VARIABLE
        System.out.println("i = " + i);
        
        System.out.println("i = " + i);
        i-=2; //DECREMENTA EN 2 EL VALOR DE LA VARIABLE
        System.out.println("i = " + i);
        
        System.out.println("i = " + i);
        i*=1; //MULTIPLICA EN 1 EL VALOR DE LA VARIABLE
        System.out.println("i = " + i);
        
        System.out.println("i = " + i);
        i*=2; //MULTIPLICA EN 2 EL VALOR DE LA VARIABLE
        System.out.println("i = " + i);
    }
    
}
