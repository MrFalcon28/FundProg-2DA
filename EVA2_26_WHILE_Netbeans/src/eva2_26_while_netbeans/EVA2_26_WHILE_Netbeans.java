
package eva2_26_while_netbeans;


public class EVA2_26_WHILE_Netbeans {

    public static void main(String[] args) {
        
        // WHILE --> MIENTRAS (QUE?)
        // CERO = N. VECES
        
        int i = 1;
        
        // IMPRIMIR LOS NUMEROS DEL 1 AL 10
        while(i <= 10){ //SE REPITE MIENTRAS LA CONDICION SEA VERDADERA
            System.out.print(i + " - ");
            i++;
        }
        System.out.println("");
       
        i = 10;
        // IMPRIMIR LOS NUMEROS DEL 10 AL 1
         while(i >= 1){ 
            System.out.print(i + " - ");
            i--;
        }
    }
    
}
